"""PlatformIO pre-build script: optional first-boot defaults from .env.

Values from the environment or a local `.env` file are written to
include/secrets.h (git-ignored). They only seed the configuration on the very
first boot (or after a factory reset); afterwards everything is edited in the
web admin panel and stored on the device.

Recognised keys: SSID, PASSWORD, LANGUAGE (EN|LV), DATE_FORMAT, HA_URL, HA_TOKEN
"""
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except Exception:  # running standalone
    ROOT = os.getcwd()

KEYS = {
    "SSID": "WIFI_SSID",
    "PASSWORD": "WIFI_PASSWORD",
    "LANGUAGE": "LANGUAGE",
    "DATE_FORMAT": "DATE_FORMAT",
    "HA_URL": "HA_URL",
    "HA_TOKEN": "HA_TOKEN",
}


def read_env_file(path):
    values = {}
    if not os.path.isfile(path):
        return values
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            value = value.split(" #", 1)[0].strip().strip('"').strip("'")
            values[key.strip()] = value
    return values


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate():
    file_values = read_env_file(os.path.join(ROOT, ".env"))
    lines = ["// Auto-generated by build/generate_secrets.py - do not commit", "#pragma once"]
    for key, macro in KEYS.items():
        value = os.environ.get(key) or file_values.get(key)
        if value:
            lines.append(f"#define {macro} {c_string(value)}")
    content = "\n".join(lines) + "\n"
    path = os.path.join(ROOT, "include", "secrets.h")
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != content:  # avoid needless full rebuilds
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        print("[generate_secrets] wrote include/secrets.h")


generate()
