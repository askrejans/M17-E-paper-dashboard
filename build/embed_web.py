"""PlatformIO pre-build script: embed web/ assets into the firmware.

Every file in web/ is gzip-compressed and emitted as a PROGMEM byte array in
include/generated/web_assets.h together with a lookup table. The server sends
them with `Content-Encoding: gzip`, so the device needs no filesystem upload
and the admin UI always matches the firmware version.
"""
import gzip
import os

try:
    Import("env")  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except Exception:
    ROOT = os.getcwd()

WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "include", "generated", "web_assets.h")
MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
}


def ident(rel):
    return "asset_" + "".join(c if c.isalnum() else "_" for c in rel)


def generate():
    files = []
    for dirpath, _, names in os.walk(WEB):
        for name in sorted(names):
            if name.startswith("."):
                continue
            full = os.path.join(dirpath, name)
            rel = "/" + os.path.relpath(full, WEB).replace(os.sep, "/")
            files.append((rel, full))
    files.sort()

    parts = [
        "// Auto-generated by build/embed_web.py from web/ - do not edit",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "struct WebAsset { const char *path; const char *mime; const uint8_t *data; size_t len; };",
        "",
    ]
    table = []
    total = 0
    for rel, full in files:
        with open(full, "rb") as fh:
            raw = fh.read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(gz)
        name = ident(rel)
        body = ",".join(str(b) for b in gz)
        parts.append(f"static const uint8_t {name}[] PROGMEM = {{{body}}};")
        mime = MIME.get(os.path.splitext(rel)[1], "application/octet-stream")
        table.append(f'  {{"{rel}", "{mime}", {name}, {len(gz)}}},')
    parts.append("")
    parts.append("static const WebAsset WEB_ASSETS[] = {")
    parts.extend(table)
    parts.append("};")
    parts.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
    content = "\n".join(parts) + "\n"

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if old != content:
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write(content)
        print(f"[embed_web] {len(files)} assets, {total} bytes gzipped")


generate()
